"use client";

import { useEffect, useRef, useState } from "react";
import { Check, Copy, Download } from "lucide-react";
import { exportFile } from "@/lib/api";
import type { DemoDocument, DocumentContext, RecordedRun, RecordedStep } from "@/lib/api";
import { DownloadButton, ErrorNotice, Status } from "./primitives";

export interface RecordedOutputClassification {
  kind: "source_extract" | "word_count" | "provider" | "unmatched" | "legacy" | "none";
  label: string;
  explanation?: string;
}

export function classifyRecordedOutput(
  run?: { agentName?: string; source?: string; steps?: RecordedStep[] } | null,
  step?: RecordedStep | null,
  context?: DocumentContext | null
): RecordedOutputClassification {
  const generationStep = step ?? run?.steps?.find(s => s.stepType === "generation");
  const output = generationStep?.outputData;
  const answer = typeof output?.answer === "string" ? output.answer : null;

  if (answer === null) {
    return { kind: "none", label: "Recorded answer" };
  }

  if (run?.source === "legacy-fixture") {
    return { kind: "legacy", label: "Recorded answer" };
  }

  const providerError = generationStep?.inputData?.providerError;
  if (providerError) return {
    kind: "none", label: "Recorded answer",
    explanation: "Provider call was attempted but recorded an error; output is not a successfully generated provider answer."
  };

  const retrieval = run?.steps?.find(s => s.stepType === "retrieval");
  const expected = generationStep?.inputData?.expectedAnswer;
  const countOperation = retrieval?.inputData?.operation === "word_count";
  if (countOperation && typeof expected === "string" && answer === expected) return {
    kind: "word_count", label: "Recorded word count",
    explanation: "Matches the locally computed expected count recorded for this run."
  };

  const evidence = generationStep?.inputData?.answerEvidence as { answer?: unknown } | undefined;
  const model = generationStep?.inputData?.model;
  if (typeof model === "string" && model.trim() && evidence?.answer === answer) return {
    kind: "provider", label: "Provider-generated answer",
    explanation: `Generated by external provider (${model}). Evidence checks verify citations and quotes, not semantic correctness.`
  };

  // 3. Literal source extract checks
  const inputDoc = generationStep?.inputData?.document as DemoDocument | undefined;
  const citation = typeof output?.citation === "string" ? output.citation : null;
  const contextDoc = citation ? context?.documents?.find(d => d.documentId === citation) : undefined;
  const citedDoc = contextDoc ?? (inputDoc?.documentId === citation ? inputDoc : undefined);
  const docText = typeof citedDoc?.text === "string" ? citedDoc.text : null;

  if (docText !== null && docText.includes(answer) && answer.trim().length > 0) {
    return {
      kind: "source_extract",
      label: "Literal source extract",
      explanation: "Matching source text does not establish whether the user's question was answered."
    };
  }

  if (countOperation) return {
    kind: "unmatched", label: "Recorded answer",
    explanation: "Word count operation was recorded, but this output does not match its recorded expected count."
  };

  if (docText !== null && !docText.includes(answer)) {
    return {
      kind: "unmatched",
      label: "Recorded answer",
      explanation: "Recorded text does not match the cited source document."
    };
  }

  return {
    kind: "none",
    label: "Recorded answer"
  };
}

export function DocumentEvidence({ run, context, error }: {
  run: RecordedRun; context: DocumentContext | null; error: string;
}) {
  const [copyState, setCopyState] = useState<"idle" | "copied" | "failed">("idle");
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const sources = useRef<HTMLDetailsElement>(null);
  useEffect(() => () => { if (timer.current) clearTimeout(timer.current); }, []);
  const generation = run.steps.find(step => step.stepType === "generation");
  const output = generation?.outputData;
  const evidence = generation?.inputData?.answerEvidence as { quotes?: unknown[]; supported?: boolean } | undefined;
  const providerError = generation?.inputData?.providerError as { message?: string } | undefined;
  const citation = typeof output?.citation === "string" ? output.citation : null;
  const source = context?.documents.find(document => document.documentId === citation);
  const answer = typeof output?.answer === "string" ? output.answer : null;
  const classification = classifyRecordedOutput(run, generation, context);

  function inspectSource() {
    if (!sources.current) return;
    sources.current.open = true;
    const sourceElement = sources.current.querySelector<HTMLElement>('[data-cited="true"]');
    sourceElement?.scrollIntoView({ block: "center" });
    sourceElement?.focus({ preventScroll: true });
  }
  async function copyAnswer() {
    if (answer === null) return;
    try { await navigator.clipboard.writeText(answer); setCopyState("copied"); }
    catch { setCopyState("failed"); }
    if (timer.current) clearTimeout(timer.current);
    timer.current = setTimeout(() => setCopyState("idle"), 3000);
  }
  return <section className="document-evidence" aria-label="Recorded document evidence">
    <div className="section-heading"><h2>Recorded answer <span className="status neutral">{classification.label}</span></h2><div className="heading-actions">{answer !== null && <><button type="button" className="icon-button" title="Copy answer" aria-label="Copy answer" onClick={() => void copyAnswer()}>{copyState === "copied" ? <Check size={16} /> : <Copy size={16} />}</button><button type="button" className="icon-button" title="Download answer" aria-label="Download answer" onClick={() => exportFile(new Blob([answer], { type: "text/plain;charset=utf-8" }), `${run.runId}-answer.txt`)}><Download size={16} /></button></>}<Status value={run.outcome} /></div></div>
    {copyState !== "idle" && <p className="quiet-label" role="status">{copyState === "copied" ? "Answer copied." : "Clipboard unavailable. Download the answer instead."}</p>}
    <div className="answer-evidence-layout"><div className="answer-result"><p className="recorded-answer">{typeof output?.answer === "string" ? output.answer : "No answer recorded"}</p>{classification.explanation && <p className="quiet-label" style={{ marginTop: 10 }}>{classification.explanation}</p>}</div><div className="answer-support">
    <p className="answer-citation"><span>Cited source</span>{source ? <button type="button" className="citation-link" onClick={inspectSource}>{source.title}</button> : <strong>{citation ?? "None"}</strong>}</p>
    {providerError?.message && <ErrorNotice message={providerError.message} />}
    {evidence?.supported === false && <p className="quiet-label">No supported answer found in the selected document.</p>}
    {!!evidence?.quotes?.length && <h3 className="evidence-heading">Supporting passages</h3>}
    {evidence?.quotes?.map((quote, index) => typeof quote === "string" && <blockquote key={index}>{quote}</blockquote>)}
    {typeof generation?.inputData?.model === "string" && <p className="quiet-label">Evidence checks verify source quotes and citation, not every factual claim.</p>}
    {error && <ErrorNotice message={error} />}
    </div></div>
    {context && <details ref={sources}><summary>Source documents ({context.documents.length})</summary>
      <div className="section-heading execution-sources"><h3>Execution sources</h3><DownloadButton value={context} name={`${run.runId}-sources.json`} /></div>
      {context.documents.map(document => <article className="source-record" key={document.documentId} data-cited={document.documentId === citation} tabIndex={-1}>
        <h3>{document.title} <span className="status neutral">{document.current ? "Current" : "Archived"}</span></h3>
        <p>{document.text}</p><p className="mono muted">{document.documentId}{document.documentId === citation ? " / cited" : ""}</p>
      </article>)}
    </details>}
  </section>;
}
